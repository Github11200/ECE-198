#!/usr/bin/env bash
# Generate the git-ignored local_config.h, which overrides the Convex settings
# in secrets.h with the deployment this repo is linked to:
#   CONVEX_URL           <- CONVEX_URL in ../.env.local (written by `npx convex dev`)
#   FEEDBACK_READ_TOKEN  <- FEEDBACK_READ_TOKEN in ../.env
# A local backend URL (127.0.0.1) is rewritten to this laptop's Wi-Fi IP so the
# board can reach it on a network without client isolation (not eduroam).
# Wi-Fi credentials stay in secrets.h; this script never reads that file.
# Rerun after switching deployments or rotating the token, then reflash.
set -euo pipefail
cd "$(dirname "$0")/.."
get() { grep -E "^$1=" "$2" | tail -1 | cut -d= -f2- | tr -d '"'; }
URL="$(get CONVEX_URL ../.env.local)"
TOKEN="$(get FEEDBACK_READ_TOKEN ../.env)"
[[ -n "$URL" ]] || { echo "CONVEX_URL missing in ../.env.local (run npx convex dev)" >&2; exit 1; }
[[ -n "$TOKEN" ]] || { echo "FEEDBACK_READ_TOKEN missing in ../.env" >&2; exit 1; }
if [[ "$URL" == *"127.0.0.1"* || "$URL" == *"localhost"* ]]; then
  IFACE="$(ip -o link show | awk -F': ' '$2 ~ /^wl/ {print $2; exit}')"
  IP="$(ip -4 -o addr show "$IFACE" | awk '{split($4, a, "/"); print a[1]; exit}')"
  URL="${URL/127.0.0.1/$IP}"; URL="${URL/localhost/$IP}"
fi
cat > local_config.h <<CFG
#pragma once
// Generated by tools/write-local-config.sh from ../.env.local and ../.env.
#undef CONVEX_URL
#define CONVEX_URL "$URL"
#undef FEEDBACK_READ_TOKEN
#define FEEDBACK_READ_TOKEN "$TOKEN"
CFG
echo "local_config.h: CONVEX_URL=$URL, read token set"
